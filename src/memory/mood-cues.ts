// 落ち込みの cue 検出(③b・2026-06-24)。現在の会話文から「相手が沈んでいそうか」を素朴に拾う純粋関数。
//
// 旧「心(valence の減衰平均 recentUserTone → 正valence記憶を recall で加点)」は撤去した。複雑な割に体感に出ず、
// 履歴の数値平均は「いま落ち込んでいるか」とずれていた。代わりに**現在の発話**の cue で判定し、想起バイアスでは
// なく moment ヒント(prompt)で「明るい話題にそっと触れてよい」と促す方式へ簡素化(context-builder が使う)。
// ※ 言語的な一般 cue であってキャラの個性ではない(§5.1 のハードコード禁止には当たらない)。

// 落ち込み・つらさの合図(日本語・調整可)。強い否定的トーンに絞り、日常の軽口は拾わない。
const LOW_MOOD_CUES = [
  'つらい',
  '辛い',
  'しんどい',
  'きつい',
  '疲れた',
  'つかれた',
  'だるい',
  '最悪',
  '落ち込',
  '凹',
  '泣',
  '悲しい',
  'かなしい',
  'さみしい',
  '寂しい',
  '不安',
  '憂鬱',
  'ゆううつ',
  'やる気が出ない',
  'もうだめ',
  'うまくいかない',
  '失敗した',
  '怒られた',
  '嫌になる',
  'いやになる',
];

/** 現在の会話文に落ち込みの cue が含まれるか(素朴・既定 false)。 */
export function seemsDown(text: string): boolean {
  return LOW_MOOD_CUES.some((cue) => text.includes(cue));
}

